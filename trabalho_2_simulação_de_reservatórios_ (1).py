def calculate_difusividade(k, phi, mi, ct):
    return k / (phi * mi * ct) * 0.0003484


def calculate_neumann(p0, qw, mi, L, k, A, D, x, t):
    sqrt_term = np.sqrt(4 * D * t / (np.pi * L ** 2))
    exp_term = np.exp(-x ** 2 / (4 * D * t))
    erfc_term = erfc(x / np.sqrt(4 * D * t))
    return p0 - (119.6 * qw * mi * L / (k * A)) * (sqrt_term * exp_term - (x / L) * erfc_term)


D = calculate_difusividade(k, phi, mi, ct)
