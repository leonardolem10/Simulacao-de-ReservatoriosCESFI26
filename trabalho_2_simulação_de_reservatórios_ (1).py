import numpy as np
import matplotlib.pyplot as plt
from scipy.special import erfc
import math as mt
import time  # Para medir tempo computacional

# PARÂMETROS DO PROBLEMA
Pe = 300
k = 20
mi = 0.8
phi = 0.18
ct = 150e-6
L = 300
qw = -240  # produção negativa
A_sec = 4000


# DISCRETIZAÇÃO
dx = 15
dt = 0.001
Nx = int(L / dx) + 2
tempo_total = 20
Nt = int(tempo_total / dt)

# PARÂMETROS NUMÉRICOS

eta = (k / (phi * mi * ct)) * 0.0003484
rx = dt / dx ** 2

if rx * eta > 0.25:
    raise ValueError("Condição de estabilidade não satisfeita!")

# MATRIZ A

A = np.zeros((Nx - 2, Nx - 2))
for i in range(Nx - 2):
    if i == 0:
        A[i, i] = 1 + rx * eta
        A[i, i + 1] = -rx * eta
    elif i == Nx - 3:
        A[i, i - 1] = -4 / 3 * rx * eta
        A[i, i] = 1 + 4 * rx * eta
    else:
        A[i, i - 1] = -rx * eta
        A[i, i] = 1 + 2 * rx * eta
        A[i, i + 1] = -rx * eta



# MÉTODOS ITERATIVOS

def Gauss_Seidel(A, b, x0=None, tol=1e-9, max_iter=5000):
    x = np.zeros_like(b) if x0 is None else x0.copy()
    for _ in range(max_iter):
        x_old = x.copy()
        for i in range(len(b)):
            s1 = np.dot(A[i, :i], x[:i])
            s2 = np.dot(A[i, i + 1:], x_old[i + 1:])
            x[i] = (b[i] - s1 - s2) / A[i, i]
        if np.linalg.norm(x - x_old, np.inf) < tol:
            break
    return x


def Jacobi(A, b, x0=None, tol=1e-9, max_iter=5000):
    x = np.zeros_like(b) if x0 is None else x0.copy()
    D = np.diag(A)
    R = A - np.diagflat(D)
    for _ in range(max_iter):
        x_new = (b - np.dot(R, x)) / D
        if np.linalg.norm(x_new - x, np.inf) < tol:
            return x_new
        x = x_new
    return x



# MÉTODO EXPLÍCITO
start_exp = time.time()

