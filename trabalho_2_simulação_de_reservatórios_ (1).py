for n in range(0, Nt - 1):
    p_exp[n + 1, 0] = p_exp[n, 1] + ((119.6 * qw * mi * dx) / (2 * k * A_sec))
    p_exp[n + 1, 1] = eta * rx * p_exp[n, 2] + (1 - eta * rx) * p_exp[n, 1] + eta * rx * qw * (119.6 * mi * dx) / (
                k * A_sec)
    for i in range(2, Nx - 2):
        p_exp[n + 1, i] = rx * eta * p_exp[n, i - 1] + (1 - 2 * rx * eta) * p_exp[n, i] + rx * eta * p_exp[n, i + 1]
    p_exp[n + 1, -2] = (4 / 3) * rx * eta * p_exp[n, -3] + (1 - 4 * rx * eta) * p_exp[n, -2] + (8 / 3) * rx * eta * Pe
    p_exp[n + 1, -1] = Pe

tempo_exp = time.time() - start_exp


# MÉTODO IMPLÍCITO - GAUSS-SEIDEL

start_gs = time.time()

