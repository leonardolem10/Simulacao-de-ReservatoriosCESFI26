    F[-1] += (8 / 3) * rx * eta * Pe
    b = pressao_jacobi[n - 1, 1:-1] + F
    p_new = Jacobi(A, b, pressao_jacobi[n - 1, 1:-1])
    pressao_jacobi[n, 1:-1] = p_new
    pressao_jacobi[n, -1] = Pe
