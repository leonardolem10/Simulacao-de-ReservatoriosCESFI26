# CÁLCULO DOS ERROS

def erro_percentual(pressao_numerica, pressao_analitica):
    # Evita divisão por zero
    with np.errstate(divide='ignore', invalid='ignore'):
        erro = np.abs((pressao_numerica - pressao_analitica) / pressao_analitica) * 100
        erro[np.isnan(erro)] = 0  # se a pressão analítica for zero, define erro como 0%
    return erro


